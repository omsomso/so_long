#include "../so_long.h"

void	print_matrix(char **m, int x, int y)
{
	int	i;
	int	j;

	i = 0;
	j = 0;
	while (i <= y)
	{
		while (j <= x)
		{
			ft_putchar_fd(m[i][j], 1);
			j++;
		}
		j = 0;
		i++;
		ft_putchar_fd('\n', 1);
	}
}
